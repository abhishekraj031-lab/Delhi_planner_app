// Rebuilds src/data/photos.ts from assets/photos (one <place-id>.jpg per place), recording each photo's size.
// Run after adding or replacing photos:  node scripts/generate-photos-index.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'photos');

function jpegSize(file) {
  const b = fs.readFileSync(file);
  let i = 2;
  while (i < b.length) {
    if (b[i] !== 0xff) { i++; continue; }
    const marker = b[i + 1];
    const len = b.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xcf && ![0xc4, 0xc8, 0xcc].includes(marker)) return { h: b.readUInt16BE(i + 5), w: b.readUInt16BE(i + 7) };
    i += 2 + len;
  }
  throw new Error('No size in ' + file);
}

const ids = fs.readdirSync(dir).filter((f) => f.endsWith('.jpg')).map((f) => f.replace(/\.jpg$/, '')).sort();
const lines = ids.map((id) => {
  const { w, h } = jpegSize(path.join(dir, id + '.jpg'));
  return `  '${id}': { src: require('../../assets/photos/${id}.jpg'), w: ${w}, h: ${h} },`;
}).join('\n');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'photos.ts'),
  `// Generated by scripts/generate-photos-index.js. Metro needs static requires.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport type PhotoEntry = { src: ImageSourcePropType; w: number; h: number };\nexport const photos: Record<string, PhotoEntry> = {\n${lines}\n};\n`);
console.log(`Wrote ${ids.length} photo entries.`);
