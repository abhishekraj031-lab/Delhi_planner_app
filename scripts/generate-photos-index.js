// Rebuilds src/data/photos.ts from assets/photos (one <place-id>.jpg per place).
// Run after adding or replacing photos:  node scripts/generate-photos-index.js
const fs = require('fs');
const path = require('path');
const dir = path.join(__dirname, '..', 'assets', 'photos');
const ids = fs.readdirSync(dir).filter((f) => f.endsWith('.jpg')).map((f) => f.replace(/\.jpg$/, '')).sort();
const lines = ids.map((id) => `  '${id}': require('../../assets/photos/${id}.jpg'),`).join('\n');
fs.writeFileSync(path.join(__dirname, '..', 'src', 'data', 'photos.ts'),
  `// Generated by scripts/generate-photos-index.js. Metro needs static requires.\nimport type { ImageSourcePropType } from 'react-native';\n\nexport const photos: Record<string, ImageSourcePropType> = {\n${lines}\n};\n`);
console.log(`Wrote ${ids.length} photo entries.`);
